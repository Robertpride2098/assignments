Toddler_age = ['3', '4', '13', '20', '65']
for age in Toddler_age:
    if age < '2':
        print("You are a toddler.")
    elif age < '4':
        print("You are a toddler.")
    elif age < '13':
        print("You are a kid.")
    elif age < '20':
        print("You are a teenager.")
    elif age < '65':
        print("You are an adult.")
    else:
        print("You are an elder.")